package cwrapmsg

import (
	"flag"
	"go/ast"
	"regexp"
	"strings"

	"golang.org/x/tools/go/analysis"
)

func NewAnalyzer(cfg *Config) *analysis.Analyzer {
	var flagSet flag.FlagSet
	if cfg == nil {
		cfg = &Config{}
		flagSet = flags(cfg)
	}

	analyser := &analysis.Analyzer{
		Name:  "cwrapmsg",
		Doc:   "Checks messages that are passed to errors.Wrap, errors.Wrapf and fmt.Errorf",
		URL:   "https://github.com/mrsubudei/cwrapmsg",
		Flags: flagSet,
		Run: func(pass *analysis.Pass) (any, error) {
			Run(pass, *cfg)

			return nil, nil
		},
	}

	return analyser
}

func flags(opts *Config) flag.FlagSet {
	fs := flag.NewFlagSet("cwrapmsg", flag.ContinueOnError)

	fs.BoolVar(&opts.IgnoreCyrillic, "ignore-cyrillic", false, "skip messages containing cyrillic symbols")
	fs.BoolVar(&opts.CaseInsensitive, "case-insensitive", false, "perform case-insensitive comparison")

	return *fs
}

func Run(pass *analysis.Pass, cfg Config) {
	for _, file := range pass.Files {
		if isGenerated(pass, file) {
			continue
		}

		wrapPackageName := getPackageNameOrAlias(file, "errors", "github.com/pkg/errors")
		fmtPackageName := getPackageNameOrAlias(file, "fmt", "fmt")

		handle(pass, file, cfg, wrapPackageName, fmtPackageName)
	}
}

var (
	generatedFileNameRegexp = regexp.MustCompile(`\.pb\.|_gen\.go$`)
	generatedCommentRegexp  = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)
)

const cgoGeneratedComment = "// Code generated by cmd/cgo; DO NOT EDIT."

// isGenerated reports whether the file is generated. The files of packages
// which use cgo are processed by cmd/cgo and have its "Code generated" comment,
// so the comment is ignored, the original file name is taken from line directives.
func isGenerated(pass *analysis.Pass, file *ast.File) bool {
	for _, group := range file.Comments {
		if group.Pos() > file.Package {
			break
		}

		for _, comment := range group.List {
			text := strings.TrimSpace(comment.Text)
			if text != cgoGeneratedComment && generatedCommentRegexp.MatchString(text) {
				return true
			}
		}
	}

	return generatedFileNameRegexp.MatchString(pass.Fset.Position(file.Package).Filename)
}
